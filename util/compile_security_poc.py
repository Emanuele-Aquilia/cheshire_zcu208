#!/usr/bin/env python3
import os
import subprocess
import sys
import re
import shutil
import argparse

# Define paths
WORKSPACE_ROOT = os.path.abspath(os.path.dirname(os.path.dirname(__file__)))
TESTS_DIR = os.path.join(WORKSPACE_ROOT, "sw/tests")
HOST_BIN_DIR = os.path.join(WORKSPACE_ROOT, "sw/deps/cva6-sdk/buildroot/output/host/bin")
COMPILER_PATH = os.path.join(HOST_BIN_DIR, "riscv64-buildroot-linux-gnu-gcc")
AR_PATH = os.path.join(HOST_BIN_DIR, "riscv64-buildroot-linux-gnu-ar")
STRIP_PATH = os.path.join(HOST_BIN_DIR, "riscv64-buildroot-linux-gnu-strip")
ROOTFS_USR_BIN = os.path.join(WORKSPACE_ROOT, "sw/deps/cva6-sdk/rootfs/usr/bin")

def calculate_offsets(libpath):
    readelf_bin = os.path.join(WORKSPACE_ROOT, "sw/deps/cva6-sdk/buildroot/output/host/bin/riscv64-buildroot-linux-gnu-readelf")
    if not os.path.exists(readelf_bin):
        readelf_bin = "readelf"

    try:
        out = subprocess.check_output([readelf_bin, "-s", libpath]).decode("utf-8", errors="ignore")
    except Exception as e:
        print(f"  -> warning: failed to run readelf: {e}")
        return None, None

    mpi_exp_mod_offset = None
    ctr_drbg_init_offset = None

    for line in out.splitlines():
        if "mpi_exp_mod" in line and "GLOBAL" in line:
            parts = line.split()
            if len(parts) >= 8:
                mpi_exp_mod_offset = int(parts[1], 16)
        if "ctr_drbg_init" in line and "GLOBAL" in line:
            parts = line.split()
            if len(parts) >= 8 and parts[7] == "ctr_drbg_init":
                ctr_drbg_init_offset = int(parts[1], 16)

    if mpi_exp_mod_offset is None or ctr_drbg_init_offset is None:
        print("  -> warning: could not find function symbols in elf")
        return None, None

    # c.nop, c.nop, c.nop, c.nop, unimpl, c.nop
    pattern_bytes = b"\x01\x00\x01\x00\x01\x00\x01\x00\x00\x00\x01\x00"

    try:
        with open(libpath, "rb") as f:
            data = f.read()
    except Exception as e:
        print(f"  -> warning: failed to read elf bytes: {e}")
        return None, None

    idx = data.find(pattern_bytes)
    if idx == -1:
        print("  -> warning: could not find ONE_OFFSET pattern in elf")
        return None, None

    one_offset = idx + 8
    
    if data.find(pattern_bytes, idx + 1) != -1:
        print("  -> warning: multiple occurrences of ONE_OFFSET pattern found")
        return None, None

    return mpi_exp_mod_offset, one_offset

def build_mbedtls(mbedtls_root_dir):
    if not os.path.exists(mbedtls_root_dir):
        return True
    
    # Ensure default attack_offsets.h exists for the first build
    parent_dir = os.path.dirname(mbedtls_root_dir)
    header_path = os.path.join(parent_dir, "attack_offsets.h")
    if not os.path.exists(header_path):
        template = """// generated by compile_security_poc.py
#ifndef ATTACK_OFFSETS_H
#define ATTACK_OFFSETS_H

#define MPI_EXP_MOD_OFFSET 0x0
#define ONE_OFFSET 0x0

#endif /* !ATTACK_OFFSETS_H */
"""
        with open(header_path, "w") as fd:
            fd.write(template)

    print(f"Building MbedTLS library at {os.path.relpath(mbedtls_root_dir, WORKSPACE_ROOT)} using cross-compiler...")
    try:
        cmd = [
            "make",
            "-C", mbedtls_root_dir,
            f"CC={COMPILER_PATH}",
            f"AR={AR_PATH}",
            "lib"
        ]
        subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        
        # Automate the standard build offset calculation and rebuild
        lib_path = os.path.join(mbedtls_root_dir, "library/libmbedtls.so.8")
        if os.path.exists(lib_path):
            mpi_offset, one_offset = calculate_offsets(lib_path)
            if mpi_offset is not None and one_offset is not None:
                # Update header file with real offsets
                template = """// generated automatically by cross-compiler build pipeline
#ifndef ATTACK_OFFSETS_H
#define ATTACK_OFFSETS_H

#define MPI_EXP_MOD_OFFSET 0x{mpi_offset:x}
#define ONE_OFFSET 0x{one_offset:x}

#endif /* !ATTACK_OFFSETS_H */
"""
                with open(header_path, "w") as fd:
                    fd.write(template.format(mpi_offset=mpi_offset, one_offset=one_offset))
                print(f"  -> Generated attack_offsets.h with real offsets: MPI=0x{mpi_offset:x}, ONE=0x{one_offset:x}")
                
                # Rebuild with new offsets
                print("Rebuilding MbedTLS library with patched offsets...")
                bignum_c = os.path.join(mbedtls_root_dir, "library/bignum.c")
                if os.path.exists(bignum_c):
                    os.utime(bignum_c, None)
                subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
                print("  -> MbedTLS library rebuilt successfully with actual offsets.")
        
        return True
    except subprocess.CalledProcessError as e:
        print("  -> Failed to compile MbedTLS library. Skipping tests that depend on it.")
        return False

def contains_main(filepath):
    try:
        with open(filepath, "r", encoding="utf-8", errors="ignore") as f:
            content = f.read()
            if re.search(r'\bmain\s*\([^)]*\)', content):
                return True
    except Exception as e:
        pass
    return False

def build_sactv(sactv_dir, output_dir, sactv_groups=None):
    print("\n--- Running Special Build Pipeline for SACTV ---")
    if sactv_groups is not None:
        print(f"Targeting SACTV group(s): {sactv_groups}")
    else:
        print("Targeting ALL SACTV groups (warning: rootfs size will be ~2.1 GB!)")
    
    # 1. Clean SACTV build outputs
    print("Cleaning previous SACTV build outputs...")
    try:
        subprocess.run(["make", "clean"], cwd=sactv_dir, check=True)
    except subprocess.CalledProcessError as e:
        print("  -> warning: make clean failed.")

    # 2. Run make benchmark TARGET=CHESHIRE
    print("Running: make benchmark TARGET=CHESHIRE ...")
    try:
        subprocess.run(["make", "benchmark", "TARGET=CHESHIRE"], cwd=sactv_dir, check=True)
        print("  -> make benchmark completed successfully.")
    except subprocess.CalledProcessError as e:
        print("  -> FAILED to run make benchmark.")
        return

    # 2.5 Compile eviction_histogram and timing_histogram
    print("Compiling eviction_histogram and timing_histogram for CHESHIRE...")
    try:
        cmd_evict = [
            COMPILER_PATH,
            "-Iinclude/",
            "-O0", "-DON_MULTIPLE_LINES=1", "-DMMAP_ARRAY",
            "-DBOARD=CHESHIRE",
            "src/evict.c", "src/eviction_evaluation.c",
            "-o", os.path.join(sactv_dir, "eviction_histogram")
        ]
        subprocess.run(cmd_evict, cwd=sactv_dir, check=True)
        
        cmd_hist = [
            COMPILER_PATH,
            "-Iinclude/",
            "-O0", "-DON_MULTIPLE_LINES=1", "-DMMAP_ARRAY",
            "-DBOARD=CHESHIRE",
            "src/evict.c", "src/timing_histogram.c",
            "-o", os.path.join(sactv_dir, "timing_histogram")
        ]
        subprocess.run(cmd_hist, cwd=sactv_dir, check=True)
        print("  -> eviction_histogram and timing_histogram compiled successfully.")
    except subprocess.CalledProcessError as e:
        print("  -> FAILED to compile histograms.")

    # 3. Copy benchmark_output to output_dir
    src_bench_dir = os.path.join(sactv_dir, "benchmark_output")
    dest_bench_dir = os.path.join(output_dir, "benchmark_output")
    if os.path.exists(src_bench_dir):
        print(f"Deploying benchmark_output to overlay at {os.path.relpath(dest_bench_dir, WORKSPACE_ROOT)}...")
        if os.path.exists(dest_bench_dir):
            shutil.rmtree(dest_bench_dir)
        
        if sactv_groups is None:
            shutil.copytree(src_bench_dir, dest_bench_dir)
        else:
            os.makedirs(dest_bench_dir, exist_ok=True)
            for item in os.listdir(src_bench_dir):
                src_item = os.path.join(src_bench_dir, item)
                dest_item = os.path.join(dest_bench_dir, item)
                if os.path.isfile(src_item):
                    shutil.copy2(src_item, dest_item)
                elif os.path.isdir(src_item):
                    os.makedirs(dest_item, exist_ok=True)
                    for file in os.listdir(src_item):
                        src_file = os.path.join(src_item, file)
                        dest_file = os.path.join(dest_item, file)
                        if os.path.isfile(src_file):
                            matched = False
                            for group in sactv_groups:
                                if file.startswith(f"{group}_"):
                                    matched = True
                                    break
                            if matched:
                                shutil.copy2(src_file, dest_file)
            print(f"  -> Only group(s) {sactv_groups} copied.")

    # 4. Copy scripts to output_dir
    src_scripts_dir = os.path.join(sactv_dir, "scripts")
    dest_scripts_dir = os.path.join(output_dir, "scripts")
    if os.path.exists(src_scripts_dir):
        print(f"Deploying scripts to overlay at {os.path.relpath(dest_scripts_dir, WORKSPACE_ROOT)}...")
        if os.path.exists(dest_scripts_dir):
            shutil.rmtree(dest_scripts_dir)
        shutil.copytree(src_scripts_dir, dest_scripts_dir)
        print("  -> scripts deployed.")

    # 5. Copy eviction_histogram and timing_histogram
    for binary in ["eviction_histogram", "timing_histogram"]:
        src_bin = os.path.join(sactv_dir, binary)
        if os.path.exists(src_bin):
            shutil.copy2(src_bin, os.path.join(output_dir, binary))
            print(f"  -> {binary} deployed.")

    # 6. Strip binaries to reduce size
    if os.path.exists(STRIP_PATH):
        print("Stripping SACTV binaries in overlay to minimize footprint...")
        for binary in ["eviction_histogram", "timing_histogram"]:
            dest_bin = os.path.join(output_dir, binary)
            if os.path.exists(dest_bin):
                try:
                    subprocess.run([STRIP_PATH, dest_bin], check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
                except Exception:
                    pass
        for root, _, files in os.walk(dest_bench_dir):
            for file in files:
                if not file.endswith((".txt", ".sh", ".py", ".md", ".json")):
                    file_path = os.path.join(root, file)
                    try:
                        subprocess.run([STRIP_PATH, file_path], check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
                    except Exception:
                        pass
        print("  -> Stripping complete.")

def compile_poc():
    if not os.path.exists(COMPILER_PATH):
        print(f"Error: Cross-compiler not found at {COMPILER_PATH}")
        print("Please build cva6-sdk images once to generate the buildroot toolchain.")
        sys.exit(1)

    if not os.path.exists(TESTS_DIR):
        print(f"Error: tests directory not found at {TESTS_DIR}")
        sys.exit(1)

    parser = argparse.ArgumentParser(description="Compile Security PoCs for Cheshire")
    parser.add_argument("--sactv-group", type=str, default=None,
                        help="Comma-separated list of SACTV group prefixes to copy (e.g. '00' or '00,01'). Defaults to deploying all if not specified.")
    args = parser.parse_args()

    sactv_groups = None
    if args.sactv_group is not None:
        if args.sactv_group.strip().lower() == "all":
            sactv_groups = None
        else:
            sactv_groups = [g.strip() for g in args.sactv_group.split(",") if g.strip()]
    elif sys.stdin.isatty():
        try:
            print("\nSACTV benchmark suite has 88 groups (00 to 87). Deploying all groups takes ~2.1 GB and will crash the kernel boot.")
            ans = input("Enter SACTV group prefix to deploy (e.g. 00), 'all' to deploy everything, or 'none' to skip SACTV [default: 00]: ").strip()
            if not ans:
                sactv_groups = ["00"]
            elif ans.lower() == "none":
                sactv_groups = ["none"]
            elif ans.lower() == "all":
                sactv_groups = None
            else:
                sactv_groups = [g.strip() for g in ans.split(",") if g.strip()]
        except (KeyboardInterrupt, EOFError):
            print("\nInterrupted. Defaulting SACTV group to '00'.")
            sactv_groups = ["00"]
    else:
        # Non-interactive default to "00" to prevent crash
        sactv_groups = ["00"]

    # Find all subdirectories in sw/tests
    submodules = [d for d in os.listdir(TESTS_DIR) 
                  if os.path.isdir(os.path.join(TESTS_DIR, d)) and d not in ('.git', 'build')]

    if not submodules:
        print("No test submodules found in sw/tests.")
        sys.exit(0)

    print(f"Found test submodules: {', '.join(submodules)}")

    for submodule in submodules:
        submodule_dir = os.path.join(TESTS_DIR, submodule)
        output_dir = os.path.join(ROOTFS_USR_BIN, submodule)
        os.makedirs(output_dir, exist_ok=True)

        # Handle SACTV as a special case
        if submodule == "SACTV":
            if sactv_groups and "none" in [g.lower() for g in sactv_groups]:
                print("Skipping SACTV build as requested.")
            else:
                build_sactv(submodule_dir, output_dir, sactv_groups)
            continue

        # Check and compile MbedTLS if present in this submodule
        mbedtls_root = os.path.join(submodule_dir, "mbedtls-key-leak/mbedtls")
        if not os.path.exists(mbedtls_root):
            mbedtls_root = os.path.join(submodule_dir, "mbedtls")
        
        mbedtls_ok = True
        if os.path.exists(os.path.join(mbedtls_root, "library")):
            mbedtls_ok = build_mbedtls(mbedtls_root)

        print(f"\nCompiling binaries for '{submodule}' to: {output_dir}\n")

        # Traverse the submodule directory
        for root, dirs, files in os.walk(submodule_dir):
            dirs[:] = [d for d in dirs if d not in ('mbedtls', 'module', '.git', 'build', '.idea', 'keys')]

            all_files = [f for f in files if f.endswith((".c", ".S", ".s"))]
            if not all_files:
                continue

            main_files = []
            helper_files = []

            for f in all_files:
                filepath = os.path.join(root, f)
                if f.endswith(".c") and contains_main(filepath):
                    main_files.append(f)
                else:
                    helper_files.append(f)

            if not main_files:
                continue

            rel_path = os.path.relpath(root, submodule_dir)
            dir_prefix = rel_path.replace(os.sep, "_") if rel_path != "." else ""

            for main_file in main_files:
                main_base = main_file.rsplit(".", 1)[0]
                
                if (main_base == "main" or main_base == dir_prefix) and dir_prefix:
                    binary_name = dir_prefix
                elif dir_prefix:
                    binary_name = f"{dir_prefix}_{main_base}"
                else:
                    binary_name = main_base

                if "mbedtls-key-leak" in root and not mbedtls_ok:
                    print(f"Skipping {binary_name} (MbedTLS library not compiled)")
                    continue

                sources = [os.path.join(root, main_file)]
                for h in helper_files:
                    sources.append(os.path.join(root, h))

                output_bin = os.path.join(output_dir, binary_name)

                print(f"Compiling {binary_name}...")
                
                cmd = [
                    COMPILER_PATH,
                    "-O3",
                    "-static",
                    f"-I{submodule_dir}",
                    f"-I{root}",
                ]
                if submodule == "A_security_RISC":
                    cmd.append("-DU74")

                if "mbedtls-key-leak" in root:
                    cmd.extend([
                        f"-I{os.path.join(mbedtls_root, 'include')}",
                        f"-L{os.path.join(mbedtls_root, 'library')}",
                    ])

                cmd.extend(sources)

                if "mbedtls-key-leak" in root:
                    cmd.append("-lmbedtls")

                cmd.extend(["-o", output_bin])

                try:
                    subprocess.run(cmd, check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
                    print(f"  -> Success: {os.path.relpath(output_bin, WORKSPACE_ROOT)}")
                except subprocess.CalledProcessError as e:
                    print(f"  -> FAILED to compile {binary_name}")
                    error_msg = e.stderr.decode('utf-8', errors='ignore')
                    if len(error_msg) > 500:
                        error_msg = error_msg[:500] + "\n... (truncated)"
                    print(f"  Error: {error_msg}")

    print("\nCompilation step complete. Clearing build caches to force image repackaging...")
    cva6_sdk_dir = os.path.join(WORKSPACE_ROOT, "sw/deps/cva6-sdk")
    files_to_remove = [
        os.path.join(cva6_sdk_dir, "install64/vmlinux"),
        os.path.join(cva6_sdk_dir, "install64/uImage"),
        os.path.join(cva6_sdk_dir, "buildroot/output/images/vmlinux"),
        os.path.join(cva6_sdk_dir, "buildroot/output/images/rootfs.cpio"),
        os.path.join(cva6_sdk_dir, "buildroot/output/images/rootfs.cpio.gz"),
    ]
    for f in files_to_remove:
        if os.path.exists(f):
            try:
                os.remove(f)
            except Exception as e:
                pass

    print("Packaging updated Linux image...")
    try:
        subprocess.run(["make", "images"], cwd=cva6_sdk_dir, check=True)
        print("\nSuccessfully packaged and updated uImage and fw_payload.bin with your latest changes!")
    except subprocess.CalledProcessError as e:
        print("\nFailed to run 'make images' in cva6-sdk.")
        sys.exit(1)

if __name__ == "__main__":
    compile_poc()
